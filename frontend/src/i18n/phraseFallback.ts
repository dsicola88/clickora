function applyPhrases(text: string, phrases: Array<[string, string]>): string {
  let s = text;
  for (const [from, to] of phrases) {
    if (s.includes(from)) s = s.split(from).join(to);
  }
  return s;
}

export function phraseFallbackEn(text: string): string {
  return applyPhrases(text, PT_EN_PHRASES);
}

export function phraseFallbackEs(text: string): string {
  return applyPhrases(text, PT_ES_PHRASES);
}
